"""SMW static recompiler driver.

usage: python recomp.py <rom.smc> <out_dir> [seeds.txt ...]

Discovers 65816 code reachable from the reset/NMI/IRQ vectors (plus optional
seed files with "BBAAAA fs" lines, e.g. the runtime miss log written by the
port), and emits:
  out_dir/recomp_bank_XX.c   recompiled regions grouped by bank
  out_dir/recomp_table.c     dispatcher table (address+flag state -> region/entry)
  out_dir/interp.c           fallback interpreter (same semantics generator)
  out_dir/recomp_stats.txt   coverage summary
"""
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rom import Rom, SMW_US_SHA1
from analysis import Analyzer, FS_E, FS_NAMES
import codegen

HEADER = '''// GENERATED by tools/recomp/recomp.py from the user's Super Mario World ROM.
// Do not edit; do not redistribute (derived from copyrighted ROM code).
#include "recomp_rt.h"
'''


def load_seeds(paths):
    seeds = []
    for p in paths:
        if not os.path.exists(p):
            continue
        for line in open(p):
            line = line.split('#')[0].strip()
            if not line:
                continue
            a, f = line.split()[:2]
            fs = FS_NAMES.index(f) if f in FS_NAMES else int(f)
            seeds.append((int(a, 16), fs))
    return seeds


def main():
    rom_path, out_dir = sys.argv[1], sys.argv[2]
    seed_files = sys.argv[3:]
    rom = Rom(rom_path)
    if rom.sha1 != SMW_US_SHA1:
        print('WARNING: ROM sha1 %s does not match Super Mario World (U) %s' % (rom.sha1, SMW_US_SHA1))
    t0 = time.time()
    an = Analyzer(rom)
    reset = rom.read16(0xFFFC)
    nmi = rom.read16(0xFFEA)
    irq = rom.read16(0xFFEE)
    an.add_root(reset, FS_E, 'reset')
    for fs in range(4):
        an.add_root(nmi, fs, 'nmi')
        an.add_root(irq, fs, 'irq')
    seeds = load_seeds(seed_files)
    for a, fs in seeds:
        an.add_root(a, fs, 'seed')
    an.solve()
    n_static = len(an.blocks)
    n_spec = an.speculate()
    print('speculative roots: %d (blocks %d -> %d)' % (n_spec, n_static, len(an.blocks)))
    regs, owner = an.regions()
    print('discovered %d blocks, %d regions in %.1fs (%d seeds)' % (len(an.blocks), len(regs), time.time() - t0, len(seeds)))

    os.makedirs(out_dir, exist_ok=True)
    for old in os.listdir(out_dir):   # drop bank files from previous runs
        if old.startswith('recomp_bank_') and old.endswith('.c'):
            os.remove(os.path.join(out_dir, old))
    by_bank = {}
    for rid, (root, members) in enumerate(regs):
        by_bank.setdefault(root[0] >> 16, []).append(rid)
    written = []
    for bank, rids in sorted(by_bank.items()):
        lines = [HEADER]
        for rid in rids:
            root, members = regs[rid]
            lines.extend(codegen.gen_region(an, root, members, owner, rid))
            lines.append('')
        fn = 'recomp_bank_%02X.c' % bank
        with open(os.path.join(out_dir, fn), 'w', newline='\n') as f:
            f.write('\n'.join(lines))
        written.append(fn)

    # dispatcher table
    lines = [HEADER]
    for rid, (root, members) in enumerate(regs):
        lines.append('void %s(uint32_t entry);' % codegen.region_name(root))
    lines.append('const RecompEntry g_recomp_entries[] = {')
    ents = []
    for rid, (root, members) in enumerate(regs):
        for i, k in enumerate(members):
            ents.append((k[0] << 3 | k[1], codegen.region_name(root), i))
    ents.sort()
    for key, name, i in ents:
        lines.append('  {0x%08Xu, %s, %du},' % (key, name, i))
    lines.append('};')
    lines.append('const uint32_t g_recomp_entry_count = %d;' % len(ents))
    lines.append('const char g_recomp_rom_sha1[] = "%s";' % rom.sha1)
    with open(os.path.join(out_dir, 'recomp_table.c'), 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')

    # interpreter
    lines = [HEADER] + codegen.gen_interpreter()
    with open(os.path.join(out_dir, 'interp.c'), 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')

    # stats
    n_ins = sum(len(b.insns) for b in an.blocks.values())
    bad = sum(1 for b in an.blocks.values() if b.bad)
    code_bytes = set()
    for b in an.blocks.values():
        for ins, *_ in b.insns:
            for i in range(ins.size):
                code_bytes.add(ins.addr + i)
    with open(os.path.join(out_dir, 'recomp_stats.txt'), 'w') as f:
        f.write('rom sha1 %s\n' % rom.sha1)
        f.write('blocks %d (bad %d)\ninstructions %d\nregions %d\nentries %d\nunique code bytes %d\n' %
                (len(an.blocks), bad, n_ins, len(regs), len(ents), len(code_bytes)))
        f.write('non-ROM targets: %s\n' % ' '.join('%06X/%s' % (a, FS_NAMES[fs]) for a, fs in sorted(an.nonrom_targets)))
    print('instructions %d, bad blocks %d, unique code bytes %d, files: %s' % (n_ins, bad, len(code_bytes), ' '.join(written)))


if __name__ == '__main__':
    main()
